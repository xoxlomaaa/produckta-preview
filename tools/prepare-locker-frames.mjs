// Offline asset preparation only. The normal build uses the committed packs.
import {readFile, writeFile, mkdir, readdir, unlink} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {mobileSkyFrame} from '../src/showcase/locker/config/mobile-sky-media.mjs';
import {tabletSkyFiles} from '../src/showcase/locker/config/tablet-sky-media.mjs';
const {default: sharp} = await import(process.env.SHARP_MODULE || 'sharp');
const root = resolve('assets/showcase/locker/assets');
const dest = resolve(root, 'render-v3');
await mkdir(dest, {recursive:true});
const packs = [], report = [];
for (const [group, frames, width] of [
  ['sky-desktop', Array.from({length:190}, (_, i) => i + 1), 1152],
  ['sky-tablet', Array.from({length:tabletSkyFiles.length - 1}, (_, i) => i + 1), 0],
  ['sky-mobile', Array.from({length:190}, (_, i) => i + 1), 0],
  ['warehouse-desktop', [1, ...Array.from({length:116}, (_, i) => i + 150)], 1440],
  ['warehouse-mobile', [1, ...Array.from({length:116}, (_, i) => i + 150)], 0],
]) {
  for (let start = 0; start < frames.length; start += 48) {
    const entries = [], buffers = [];
    for (const frame of frames.slice(start, start + 48)) {
      const file = `${String(frame).padStart(4, '0')}.webp`;
      const category = group === 'sky-mobile' && mobileSkyFrame(frame) ? 'sky-mobile-overscan' : group;
      const source = await readFile(resolve(root, 'render-v1', category, file));
      let image = sharp(source);
      const original = await image.metadata();
      if (width) image = image.resize({width});
      else if (group.endsWith('-mobile')) image = image.resize({width:Math.round(original.width * .75)});
      const buffer = await image.webp({quality:74, alphaQuality:100, effort:4}).toBuffer();
      const version = group === 'sky-desktop' || group === 'warehouse-desktop' ? 'render-v2' : 'render-v1';
      entries.push([`/showcase/locker/assets/${version}/${category}/${file}`, buffer.length, original.width, original.height]);
      buffers.push(buffer);
      report.push({group, frame, bytes:buffer.length});
    }
    const buffer = Buffer.concat(buffers);
    const hash = createHash('sha256').update(buffer).digest('hex').slice(0, 10);
    const file = `${group}-${String(start / 48 + 1).padStart(2, '0')}-${hash}.bin`;
    await writeFile(resolve(dest, file), buffer);
    packs.push({url:`/showcase/locker/assets/render-v3/${file}`, entries});
  }
}
await writeFile('src/showcase/locker/config/frame-packs.mjs',
  '// Generated by tools/prepare-locker-frames.mjs; byte offsets preserve every source frame.\nexport const framePacks = '+JSON.stringify(packs)+';\n');
const kept = new Set(packs.map(pack => pack.url.split('/').at(-1)));
for (const file of await readdir(dest)) {
  if (/^[a-z]+-(?:desktop|tablet|mobile)-\d+-[a-f0-9]+\.bin$/.test(file) && !kept.has(file)) await unlink(resolve(dest, file));
}
await mkdir('output/qa/locker-loading', {recursive:true});
await writeFile('output/qa/locker-loading/assets.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify({packs:packs.length, frames:report.length, bytes:report.reduce((n, item) => n + item.bytes, 0)}));
