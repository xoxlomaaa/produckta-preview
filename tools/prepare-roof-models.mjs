import assert from 'node:assert/strict';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

export function parseGlb(bytes) {
  assert.equal(bytes.readUInt32LE(0), 0x46546c67);
  assert.equal(bytes.readUInt32LE(4), 2);
  assert.equal(bytes.readUInt32LE(8), bytes.length);
  let json, bin;
  for (let offset = 12; offset < bytes.length;) {
    const size = bytes.readUInt32LE(offset), type = bytes.readUInt32LE(offset + 4);
    const data = bytes.subarray(offset + 8, offset + 8 + size);
    assert.equal(data.length, size);
    if (type === 0x4e4f534a) json = JSON.parse(data.toString());
    if (type === 0x004e4942) bin = data;
    offset += size + 8;
  }
  assert(json && bin);return {json, bin};
}

export function viewBytes(model, index) {
  const view = model.json.bufferViews[index];
  assert.equal(view.buffer, 0);
  return model.bin.subarray(view.byteOffset || 0, (view.byteOffset || 0) + view.byteLength);
}

function encode(json, chunks) {
  const bin = Buffer.concat(chunks), source = Buffer.from(JSON.stringify(json));
  const text = Buffer.concat([source, Buffer.alloc((4 - source.length % 4) % 4, 32)]);
  const header = Buffer.alloc(20), binHeader = Buffer.alloc(8);
  header.writeUInt32LE(0x46546c67, 0);header.writeUInt32LE(2, 4);
  header.writeUInt32LE(28 + text.length + bin.length, 8);
  header.writeUInt32LE(text.length, 12);header.writeUInt32LE(0x4e4f534a, 16);
  binHeader.writeUInt32LE(bin.length, 0);binHeader.writeUInt32LE(0x004e4942, 4);
  return Buffer.concat([header, text, binHeader, bin]);
}

async function prepare() {
  const {default:sharp} = await import(process.env.SHARP_MODULE || 'sharp');
  const model = parseGlb(await readFile('assets/showcase/construction/models/roof.glb'));
  const report = {}, manifest = {};
  for (const [profile, width] of [['desktop',1024], ['mobile',512]]) {
    const json = structuredClone(model.json), replacements = new Map(), images = [];
    for (const [index, image] of json.images.entries()) {
      const source = viewBytes(model, image.bufferView), normal = image.name.includes('normal');
      const original = await sharp(source).metadata();
      const resized = sharp(source).resize({width, height:width, fit:'inside', withoutEnlargement:true});
      const candidate = await resized.webp(normal
        ? (profile === 'desktop' ? {nearLossless:true,quality:90,effort:4} : {lossless:true,effort:4})
        : {quality:92,effort:4}).toBuffer();
      const keepOriginal = profile === 'desktop' && candidate.length > source.length * .9;
      const buffer = keepOriginal ? source : candidate;
      let maxError = 0;
      if (normal && profile === 'desktop' && !keepOriginal) {
        const before = await sharp(source).removeAlpha().raw().toBuffer();
        const after = await sharp(buffer).removeAlpha().raw().toBuffer();
        for (let i = 0; i < before.length; i++) maxError = Math.max(maxError, Math.abs(before[i] - after[i]));
        assert(maxError <= 1, 'Normal-map channel error exceeds one level');
      }
      if (!keepOriginal) {
        image.mimeType = 'image/webp';
        for (const texture of json.textures.filter(texture => texture.source === index)) {
          delete texture.source;
          texture.extensions = {...texture.extensions, EXT_texture_webp:{source:index}};
        }
      }
      replacements.set(image.bufferView, buffer);
      images.push({name:image.name,before:source.length,after:buffer.length,width:keepOriginal?original.width:width,maxError});
    }
    json.extensionsUsed = [...new Set([...json.extensionsUsed, 'EXT_texture_webp'])];
    json.extensionsRequired = [...new Set([...json.extensionsRequired, 'EXT_texture_webp'])];
    const chunks = [];let offset = 0;
    for (const [index, view] of json.bufferViews.entries()) {
      const buffer = replacements.get(index) || viewBytes(model, index);
      view.byteOffset = offset;view.byteLength = buffer.length;
      const pad = Buffer.alloc((4 - buffer.length % 4) % 4);
      chunks.push(buffer, pad);offset += buffer.length + pad.length;
    }
    json.buffers[0].byteLength = offset;
    const bytes = encode(json, chunks), hash = createHash('sha256').update(bytes).digest('hex').slice(0,10);
    const filename = `roof-${profile}-${hash}.glb`;
    await writeFile('assets/showcase/construction/models/'+filename, bytes);
    manifest[profile] = {url:'/showcase/construction/models/'+filename,bytes:bytes.length};
    report[profile] = {bytes:bytes.length,images};
  }
  await writeFile('src/showcase/roof-assets.js', '// Generated by tools/prepare-roof-models.mjs.\nexport const roofAssets = '+JSON.stringify(manifest)+';\n');
  await mkdir('output/qa/roof-loading', {recursive:true});
  await writeFile('output/qa/roof-loading/assets.json', JSON.stringify(report,null,2));
  console.log(manifest);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await prepare();
